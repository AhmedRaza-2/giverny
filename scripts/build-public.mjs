#!/usr/bin/env node
// Writes data/skills.js for the browser from api/_skills.js, without any install commands.
import { writeFile } from "node:fs/promises";
import { SKILLS, UPDATED } from "../api/_skills.js";

const PUBLIC = ["id", "name", "by", "repo", "path", "cat", "official", "desc", "kind", "stars"];
const pub = SKILLS.map(s => Object.fromEntries(PUBLIC.filter(k => s[k] !== undefined).map(k => [k, s[k]])));
const out = `/* Generated by scripts/build-public.mjs from api/_skills.js. Do not edit by hand.
 * Install commands are intentionally absent: the site fetches them from /api/reveal after the GitHub check. */
window.GIVERNY_UPDATED = ${JSON.stringify(UPDATED)};
window.GIVERNY_SKILLS = ${JSON.stringify(pub, null, 1)};
`;
await writeFile(new URL("../data/skills.js", import.meta.url), out);
console.log(`data/skills.js: ${pub.length} skills, no commands.`);
